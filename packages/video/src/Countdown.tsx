export const Countdown: React.FC<{
  payload: VideoPayload;
  captions: Record<string, string>;
}> = ({ payload, captions }) => {
  const fights = [...payload.fights].sort((a, b) => a.rank - b.rank);
  const top = fights[0];
  const countdownFights = fights.slice(1).reverse(); // #5, #4, #3, #2

  // Fallback carries the finish ONLY — the event and date are already on the card's meta
  // line, and printing the outcome in both places was the duplication on screen.
  const captionFor = (f: VideoFight) =>
    captions[f.fightId] ?? f.finishLabel ?? 'Went the distance';

  let cursor = 0;
  const hookStart = cursor;
  cursor += TIMING.hook;
  const teaseStart = cursor;
  cursor += TIMING.tease;
  const cardStarts = countdownFights.map((_, i) => teaseStart + TIMING.tease + i * TIMING.perCard);
  cursor = teaseStart + TIMING.tease + countdownFights.length * TIMING.perCard;
  const payoffStart = cursor;
  cursor += TIMING.payoff;
  const ctaStart = cursor;

  // The hook's backdrop comes from the LOWEST-ranked fight with a photo — never #1.
  // The whole video is a countdown to the payoff; its photo in the opening frame,
  // even blurred, is a leak. countdownFights already runs #5 -> #2.
  const hookBackground = countdownFights.map(backgroundFor).find(Boolean) ?? null;

  return (
    <AbsoluteFill style={{ backgroundColor: COLORS.bg }}>
      <Sequence from={hookStart} durationInFrames={TIMING.hook}>
        <Hook topRating={top.rating} headline={payload.hookHeadline} backgroundSrc={hookBackground} />
      </Sequence>

      <Sequence from={teaseStart} durationInFrames={TIMING.tease}>
        <Tease fights={fights} />
      </Sequence>

      {countdownFights.map((f, i) => (
        <Sequence key={f.fightId} from={cardStarts[i]} durationInFrames={TIMING.perCard}>
          <WhooshSlide durationInFrames={TIMING.perCard}>
            <FightCard
              fight={f}
              caption={captionFor(f)}
              total={fights.length}
              background={backgroundFor(f)}
            />
          </WhooshSlide>
        </Sequence>
      ))}

      <Sequence from={payoffStart} durationInFrames={TIMING.payoff}>
        {/* The superlative is scoped by the pull, never hardcoded — a Nate Diaz list's #1
            is his highest-rated fight, not the app's. Older payloads get a claim that is
            true of any list rather than one that might not be. */}
        <Payoff
          fight={top}
          caption={captionFor(top)}
          claim={payload.payoffLabel ?? 'the highest-rated fight on this list'}
          backgroundSrc={backgroundFor(top)}
        />
      </Sequence>

      <Sequence from={ctaStart} durationInFrames={TIMING.cta}>
        <CTA />
      </Sequence>

      {/* watermark on everything except the outro */}
      <Sequence from={0} durationInFrames={ctaStart}>
        <Watermark />
      </Sequence>

      {/* film grain over every scene — the flat-digital tell is the thing it kills */}
      <Grain />
    </AbsoluteFill>
  );
};

export const countdownDuration = (fightCount: number) =>
  TIMING.hook +
  TIMING.tease +
  (fightCount - 1) * TIMING.perCard +
  TIMING.payoff +
  TIMING.cta;
